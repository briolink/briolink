var update = flag.Bool("update", false, "rewrite generate/testdata/acme/gen from the generators")

type fake func(generate.Input) (map[string][]byte, error)

func (f fake) Generate(_ context.Context, in generate.Input) (map[string][]byte, error) { return f(in) }

func files(m map[string]string) fake {
	return func(generate.Input) (map[string][]byte, error) {
		out := map[string][]byte{}
		for k, v := range m {
			out[k] = []byte(v)
		}
		return out, nil
	}
}

const header = "// Code generated by test. DO NOT EDIT.\n"

// plugins builds a project and manifests where each plugin has one spec
// kind named after itself and requires the given plugins.
func plugins(spec map[string][]string, picked ...string) (*project.Project, map[string]*project.Manifest) {
	p := &project.Project{Format: "v0", ProjectID: "t", Name: "t", GoModule: "example.com/t"}
	ms := map[string]*project.Manifest{}
	for _, n := range picked {
		p.Plugins = append(p.Plugins, project.PluginRef{Name: n, Version: "0.1.0", Options: []byte("{}")})
	}
	for n, reqs := range spec {
		m := &project.Manifest{Format: "v0", Name: n, Version: "0.1.0", Purpose: "t",
			SpecKinds: []project.SpecKind{{Kind: n, Files: "spec/*.x", Generator: "gen"}}}
		for _, r := range reqs {
			m.Requires = append(m.Requires, project.Requirement{Plugin: r, MinVersion: "0.1.0"})
		}
		ms[n] = m
	}
	return p, ms
}

func TestOrder(t *testing.T) {
	p, ms := plugins(map[string][]string{"http": {"domain"}, "domain": nil, "sqlite": nil}, "http", "sqlite", "domain")
	got, err := generate.Order(p, ms)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"domain", "http", "sqlite"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("order = %v, want %v", got, want)
	}
}

func TestOrder_CycleAndMissingNameThePlugin(t *testing.T) {
	p, ms := plugins(map[string][]string{"a": {"b"}, "b": {"a"}}, "a", "b")
	if _, err := generate.Order(p, ms); err == nil || !strings.Contains(err.Error(), "a -> b -> a") {
		t.Fatalf("cycle: %v", err)
	}
	p, ms = plugins(map[string][]string{"a": nil}, "a", "ghost")
	if _, err := generate.Order(p, ms); err == nil || !strings.Contains(err.Error(), "ghost") {
		t.Fatalf("missing plugin: %v", err)
	}
}

func TestRun_RunsInOrderUnderPluginName(t *testing.T) {
	p, ms := plugins(map[string][]string{"b": {"a"}, "a": nil}, "b", "a")
	var seen []string
	rec := func(name string) fake {
		return func(in generate.Input) (map[string][]byte, error) {
			seen = append(seen, name)
			return map[string][]byte{"x.go": []byte(header)}, nil
		}
	}
	got, err := generate.Run(context.Background(), ".", p, ms, generate.Registry{"a/a": rec("a"), "b/b": rec("b")})
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(seen, []string{"a", "b"}) {
		t.Fatalf("ran %v", seen)
	}
	if _, ok := got["a/x.go"]; !ok || len(got) != 2 {
		t.Fatalf("files = %v", got)
	}
}

func TestRun_Rejections(t *testing.T) {
	p, ms := plugins(map[string][]string{"a": nil}, "a")
	for name, tc := range map[string]struct {
		reg  generate.Registry
		want string
	}{
		"no generator":   {generate.Registry{}, "plugin a, kind a: no generator registered"},
		"no header":      {generate.Registry{"a/a": files(map[string]string{"x.go": "package x\n"})}, `"x.go" has no DO NOT EDIT header`},
		"header too low": {generate.Registry{"a/a": files(map[string]string{"x.go": "1\n2\n3\n" + header})}, "no DO NOT EDIT header"},
		"escaping path":  {generate.Registry{"a/a": files(map[string]string{"../x.go": header})}, `"../x.go" must be a clean relative path`},
		"generator fails": {generate.Registry{"a/a": fake(func(generate.Input) (map[string][]byte, error) {
			return nil, errors.New("boom")
		})}, "boom"},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := generate.Run(context.Background(), ".", p, ms, tc.reg)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want it to contain %q", err, tc.want)
			}
		})
	}
}

func TestRun_TwoKindsOnOnePath(t *testing.T) {
	p, ms := plugins(map[string][]string{"a": nil}, "a")
	ms["a"].SpecKinds = append(ms["a"].SpecKinds, project.SpecKind{Kind: "k2", Files: "spec/*.y", Generator: "gen"})
	g := files(map[string]string{"x.go": header})
	_, err := generate.Run(context.Background(), ".", p, ms, generate.Registry{"a/a": g, "a/k2": g})
	if err == nil || !strings.Contains(err.Error(), `"a/x.go" is generated twice`) {
		t.Fatalf("err = %v", err)
	}
}

func TestDiffAndCheck(t *testing.T) {
	root := t.TempDir()
	want := map[string][]byte{"a/x.go": []byte(header + "one\n"), "a/y.go": []byte(header)}
	if bad, _ := generate.Diff(root, want); len(bad) != 2 {
		t.Fatalf("no gen/ at all: %v", bad)
	}
	if err := generate.Write(root, want); err != nil {
		t.Fatal(err)
	}
	if bad, err := generate.Diff(root, want); err != nil || len(bad) != 0 {
		t.Fatalf("fresh: %v %v", bad, err)
	}
	write := func(rel, s string) {
		full := filepath.Join(root, "gen", rel)
		os.MkdirAll(filepath.Dir(full), 0o755)
		if err := os.WriteFile(full, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("a/x.go", header+"two\n")
	write("a/stray.go", "hand written")
	os.Remove(filepath.Join(root, "gen", "a", "y.go"))
	bad, _ := generate.Diff(root, want)
	if want := []string{"a/stray.go (not generated)", "a/x.go (differs)", "a/y.go (missing)"}; !reflect.DeepEqual(bad, want) {
		t.Fatalf("diff = %q, want %q", bad, want)
	}
}

// TestAcme_ThroughTheHost: the domain, http and sqlite generators, behind the
// host's interface, produce the committed generate/testdata/acme/gen exactly.
// Run with -update to rewrite that directory after a deliberate change.
func TestAcme_ThroughTheHost(t *testing.T) {
	root := filepath.Join("testdata", "acme")
	p, err := project.LoadProject(filepath.Join(root, "spec", "project.json"))
	if err != nil {
		t.Fatal(err)
	}
	ms, err := generate.LoadManifests(filepath.Join("..", "plugins"), p)
	if err != nil {
		t.Fatal(err)
	}
	reg := generate.Registry{
		generate.Key("domain", "domain"):  domaingen.Host{},
		generate.Key("http", "routes"):    httpgen.Host{},
		generate.Key("sqlite", "queries"): sqlitegen.Host{},
	}
	ctx := context.Background()
	if *update {
		out, err := generate.Run(ctx, root, p, ms, reg)
		if err != nil {
			t.Fatal(err)
		}
		if err := generate.Write(root, out); err != nil {
			t.Fatal(err)
		}
	}
	if err := generate.Check(ctx, root, p, ms, reg); err != nil {
		t.Fatal(err)
	}
}

