func TestCheck_StaleGenListsPaths(t *testing.T) {
	root := t.TempDir()
	p, ms := plugins(map[string][]string{"a": nil}, "a")
	reg := generate.Registry{"a/a": files(map[string]string{"x.go": header, "y.go": header})}
	if err := generate.Check(context.Background(), root, p, ms, reg); err == nil ||
		!strings.Contains(err.Error(), "a/x.go (missing)\n  a/y.go (missing)") {
		t.Fatalf("err = %v", err)
	}
	out, _ := generate.Run(context.Background(), root, p, ms, reg)
	if err := generate.Write(root, out); err != nil {
		t.Fatal(err)
	}
	if err := generate.Check(context.Background(), root, p, ms, reg); err != nil {
		t.Fatal(err)
	}
	os.Remove(filepath.Join(root, "gen", "a", "y.go"))
	if err := generate.Check(context.Background(), root, p, ms, reg); err == nil || !strings.Contains(err.Error(), "a/y.go (missing)") {
		t.Fatalf("one stale file must fail: %v", err)
	}
}
