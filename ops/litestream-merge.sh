#!/usr/bin/env bash
# Builds the daemon's one config from the clients' entries: ops/litestream-merge.sh <dir> <out>.
# Each <dir>/*.yml is a `dbs:` list; the output is one `dbs:` list holding all of them, in name order.
set -euo pipefail
dir=$1 out=$2
{
	echo "# Generated by ops/litestream-merge.sh from /etc/litestream/clients/*.yml. Do not edit."
	echo "dbs:"
	for f in "$dir"/*.yml; do
		[ -e "$f" ] || continue
		echo "  # $(basename "$f" .yml)"
		awk '/^dbs:/ {on = 1; next} on' "$f"
	done
} >"$out"
