// Package gen is the domain plugin's generator: it turns bounded contexts
// (spec/domain/<context>.json) into Go types, transition tables and
// dispatchers, pure-function stubs and the tests derived from each
// statechart (docs/2-architecture.md § Specs and generators, M3).
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strings"

	"github.com/briolink/briolink/core/check"
	"github.com/briolink/briolink/plugins/domain/spec"
)

// Input is what Generate needs: the project's Go module path and its
// validated contexts.
type Input struct {
	Module   string
	Contexts []*spec.Context
}

// Generate returns, for each context, files keyed by name relative to the
// plugin's directory in gen/ ("<pkg>/…", where <pkg> is the context name
// without underscores):
//
//	<pkg>/types.go              enums, values, entities
//	<pkg>/funcs.go             Funcs: every guard, action, invariant and pure function
//	<pkg>/errors.go            ErrForbidden, ErrNoTransition, InvariantError (if any statechart)
//	<pkg>/<entity>_machine.go  states, events, transition table, Select, Step
//	<pkg>/<pkg>test/derived.go the tests derived from each statechart
//	<pkg>/stubs/…              Impl, one file per function, each panicking
//
// It fails, listing every problem, before returning anything.
func Generate(in Input) (map[string][]byte, error) {
	var l check.List
	pkgs := map[string]string{}
	for _, c := range in.Contexts {
		pkg := strings.ReplaceAll(c.Context, "_", "")
		if other, dup := pkgs[pkg]; dup {
			l.Addf("context "+c.Context, "generates the same package %q as %s", pkg, other)
		}
		pkgs[pkg] = c.Context
		checkNames(&l, c)
	}
	if err := l.Err(); err != nil {
		return nil, err
	}

	out := map[string][]byte{}
	put := func(path string, w *writer) error {
		src, err := format.Source(w.b.Bytes())
		if err != nil {
			return fmt.Errorf("%s: %w\n%s", path, err, w.b.String())
		}
		out[path] = src
		return nil
	}
	for _, c := range in.Contexts {
		g := &ctxGen{module: in.Module, c: c, pkg: strings.ReplaceAll(c.Context, "_", "")}
		files := g.files()
		for _, path := range sortedKeys(files) {
			if err := put(path, files[path]); err != nil {
				return nil, err
			}
		}
	}
	return out, nil
}

// checkNames rejects spec names that would not compile as Go: parameter
// names that are keywords, since they are used as written.
func checkNames(l *check.List, c *spec.Context) {
	bad := func(p, name string) {
		if token.IsKeyword(name) {
			l.Addf(p, "%q is a Go keyword; rename it", name)
		}
	}
	for _, f := range c.Functions {
		for _, p := range f.Params {
			bad("functions["+f.Name+"].params", p.Name)
		}
	}
}

type writer struct{ b bytes.Buffer }

func (w *writer) f(format string, a ...any) { fmt.Fprintf(&w.b, format+"\n", a...) }

type ctxGen struct {
	module string
	c      *spec.Context
	pkg    string
}

func (g *ctxGen) typesPath() string { return g.module + "/gen/domain/" + g.pkg }
func (g *ctxGen) testPkg() string   { return g.pkg + "test" }
func (g *ctxGen) header(w *writer) {
	w.f("// Code generated by plugins/domain/gen from spec/domain/%s.json. DO NOT EDIT.", g.c.Context)
	w.f("")
}

func (g *ctxGen) stateful() []spec.Entity {
	var out []spec.Entity
	for _, e := range g.c.Entities {
		if e.Statechart != nil {
			out = append(out, e)
		}
	}
	return out
}

func (g *ctxGen) files() map[string]*writer {
	files := map[string]*writer{}
	files[g.pkg+"/types.go"] = g.typesFile()
	files[g.pkg+"/funcs.go"] = g.funcsFile()
	st := g.stateful()
	if len(st) > 0 {
		files[g.pkg+"/errors.go"] = g.errorsFile()
		files[g.pkg+"/"+g.testPkg()+"/derived.go"] = g.derivedFile(st)
	}
	for _, e := range st {
		files[g.pkg+"/"+snake(e.Name)+"_machine.go"] = g.machineFile(e)
	}
	files[g.pkg+"/stubs/stubs.go"] = g.stubsFile()
	for _, f := range g.c.Functions {
		files[g.pkg+"/stubs/"+f.Name+".go"] = g.stubFile(f)
	}
	return files
}

// ---- Go types ----

type typer struct {
	c    *spec.Context
	qual string // "" inside the types package, "acme." elsewhere
}

func (t typer) goType(s string) string {
	nullable := strings.HasPrefix(s, "?")
	s = strings.TrimPrefix(s, "?")
	lists := 0
	for strings.HasPrefix(s, "[]") {
		lists++
		s = s[2:]
	}
	var base string
	switch s {
	case "string", "bool":
		base = s
	case "int":
		base = "int64"
	case "time":
		base = "time.Time"
	default:
		base = t.qual + s
	}
	out := strings.Repeat("[]", lists) + base
	if nullable {
		out = "*" + out
	}
	return out
}

// uses reports whether the types mention time and any type of the context.
func uses(types ...string) (timePkg, ctxTypes bool) {
	for _, s := range types {
		s = strings.TrimPrefix(s, "?")
		for strings.HasPrefix(s, "[]") {
			s = s[2:]
		}
		switch s {
		case "time":
			timePkg = true
		case "string", "int", "bool":
		default:
			ctxTypes = true
		}
	}
	return
}

func (g *ctxGen) imports(w *writer, std []string, ctx bool, extra ...string) {
	sort.Strings(std)
	if len(std) == 0 && !ctx && len(extra) == 0 {
		return
	}
	w.f("import (")
	for _, s := range std {
		w.f("\t%q", s)
	}
	if len(std) > 0 && (ctx || len(extra) > 0) {
		w.f("")
	}
	if ctx {
		w.f("\t%q", g.typesPath())
	}
	for _, s := range extra {
		w.f("\t%q", s)
	}
	w.f(")")
	w.f("")
}

func (g *ctxGen) typesFile() *writer {
	w := &writer{}
	g.header(w)
	if g.c.Doc != "" {
		w.f("// Package %s is the %q bounded context: %s", g.pkg, g.c.Context, oneLine(g.c.Doc))
	} else {
		w.f("// Package %s is the %q bounded context.", g.pkg, g.c.Context)
	}
	w.f("package %s", g.pkg)
	w.f("")
	var all []string
	for _, v := range g.c.Values {
		for _, f := range v.Fields {
			all = append(all, f.Type)
		}
	}
	for _, e := range g.c.Entities {
		for _, f := range e.Fields {
			all = append(all, f.Type)
		}
	}
	if t, _ := uses(all...); t {
		g.imports(w, []string{"time"}, false)
	}
	t := typer{c: g.c}
	for _, e := range g.c.Enums {
		doc(w, e.Name, e.Doc, "is a closed set of values.")
		w.f("type %s string", e.Name)
		w.f("")
		w.f("const (")
		for _, v := range e.Values {
			w.f("\t%s%s %s = %q", e.Name, pascal(v), e.Name, v)
		}
		w.f(")")
		w.f("")
	}
	structs := func(name, d, fallback string, fields []spec.Field) {
		doc(w, name, d, fallback)
		w.f("type %s struct {", name)
		for _, f := range fields {
			if f.Doc != "" {
				w.f("\t// %s", oneLine(f.Doc))
			}
			w.f("\t%s %s", pascal(f.Name), t.goType(f.Type))
		}
		w.f("}")
		w.f("")
	}
	for _, v := range g.c.Values {
		structs(v.Name, v.Doc, "is an immutable value.", v.Fields)
	}
	for _, e := range g.c.Entities {
		structs(e.Name, e.Doc, "is an entity.", e.Fields)
	}
	return w
}

// params renders "name Type, …" and the arguments' types for a signature.
func (g *ctxGen) sig(t typer, f spec.Function) string {
	var ps []string
	for _, p := range f.Params {
		ps = append(ps, p.Name+" "+t.goType(p.Type))
	}
	var rs []string
	for _, r := range f.Returns {
		rs = append(rs, t.goType(r.Type))
	}
	ret := strings.Join(rs, ", ")
	if len(rs) > 1 {
		ret = "(" + ret + ")"
	}
	return fmt.Sprintf("%s(%s) %s", pascal(f.Name), strings.Join(ps, ", "), ret)
}

func (g *ctxGen) funcTypes() []string {
	var all []string
	for _, f := range g.c.Functions {
		for _, p := range f.Params {
			all = append(all, p.Type)
		}
		for _, r := range f.Returns {
			all = append(all, r.Type)
		}
	}
	return all
}

func (g *ctxGen) funcsFile() *writer {
	w := &writer{}
	g.header(w)
	w.f("package %s", g.pkg)
	w.f("")
	if t, _ := uses(g.funcTypes()...); t {
		g.imports(w, []string{"time"}, false)
	}
	t := typer{c: g.c}
	w.f("// Funcs is every function the model names: the guards, actions and")
	w.f("// invariants the statecharts call, and the pure functions routes call. An")
	w.f("// implementation is filled from the stubs package; the derived tests run")
	w.f("// against any implementation.")
	w.f("type Funcs interface {")
	for _, f := range g.c.Functions {
		w.f("\t// %s (%s)", pascal(f.Name), f.Kind)
		for _, r := range f.Rules {
			w.f("\t// - %s", oneLine(r))
		}
		w.f("\t%s", g.sig(t, f))
	}
	w.f("}")
	return w
}

func (g *ctxGen) errorsFile() *writer {
	w := &writer{}
	g.header(w)
	w.f("package %s", g.pkg)
	w.f("")
	w.f("import (")
	w.f("\t\"errors\"")
	w.f("\t\"fmt\"")
	w.f(")")
	w.f("")
	w.f("// ErrForbidden: the statechart forbids this event in this state.")
	w.f("var ErrForbidden = errors.New(\"event is forbidden in this state\")")
	w.f("")
	w.f("// ErrNoTransition: every guard for this event in this state was false.")
	w.f("var ErrNoTransition = errors.New(\"no transition fires: every guard is false\")")
	w.f("")
	w.f("// InvariantError: an action left the entity breaking an invariant. The")
	w.f("// step did not happen.")
	w.f("type InvariantError struct{ Entity, Invariant string }")
	w.f("")
	w.f("func (e *InvariantError) Error() string {")
	w.f("\treturn fmt.Sprintf(\"%%s breaks invariant %%s\", e.Entity, e.Invariant)")
	w.f("}")
	return w
}

// ---- state machines ----

func (g *ctxGen) machineFile(e spec.Entity) *writer {
	sc := e.Statechart
	w := &writer{}
	g.header(w)
	w.f("package %s", g.pkg)
	w.f("")
	var evTypes []string
	for _, ev := range sc.Events {
		for _, p := range ev.Params {
			evTypes = append(evTypes, p.Type)
		}
	}
	if t, _ := uses(evTypes...); t {
		g.imports(w, []string{"time"}, false)
	}
	t := typer{c: g.c}
	S := e.Name + "State"
	E := e.Name + "Event"
	T := e.Name + "Transition"

	w.f("// %s is the lifecycle state of a %s.", S, e.Name)
	w.f("type %s string", S)
	w.f("")
	w.f("const (")
	for _, s := range sc.States {
		if s.Doc != "" {
			w.f("\t// %s", oneLine(s.Doc))
		}
		w.f("\t%s%s %s = %q", S, pascal(s.Name), S, s.Name)
	}
	w.f(")")
	w.f("")
	w.f("// %sInitial is the state of a new %s.", e.Name, e.Name)
	w.f("const %sInitial = %s%s", e.Name, S, pascal(sc.Initial))
	w.f("")
	w.f("// Final reports whether nothing may leave the state.")
	w.f("func (s %s) Final() bool {", S)
	w.f("\tswitch s {")
	var finals []string
	for _, s := range sc.States {
		if s.Final {
			finals = append(finals, S+pascal(s.Name))
		}
	}
	if len(finals) > 0 {
		w.f("\tcase %s:", strings.Join(finals, ", "))
		w.f("\t\treturn true")
	}
	w.f("\t}")
	w.f("\treturn false")
	w.f("}")
	w.f("")

	w.f("// %s is an event a %s can receive; the types below implement it.", E, e.Name)
	w.f("type %s interface {", E)
	w.f("\tEventName() string")
	w.f("\tis%s()", E)
	w.f("}")
	w.f("")
	for _, ev := range sc.Events {
		name := e.Name + pascal(ev.Name)
		doc(w, name, ev.Doc, fmt.Sprintf("is the %s event.", ev.Name))
		w.f("type %s struct {", name)
		for _, p := range ev.Params {
			if p.Doc != "" {
				w.f("\t// %s", oneLine(p.Doc))
			}
			w.f("\t%s %s", pascal(p.Name), t.goType(p.Type))
		}
		w.f("}")
		w.f("")
		w.f("func (%s) EventName() string { return %q }", name, ev.Name)
		w.f("func (%s) is%s() {}", name, E)
		w.f("")
	}

	w.f("// %s is one row of the transition table. Rows for the same state and", T)
	w.f("// event are tried in order; Holds is nil when there is no guard, Apply when")
	w.f("// there is no action.")
	w.f("type %s struct {", T)
	w.f("\tFrom   %s", S)
	w.f("\tEvent  string")
	w.f("\tTo     %s", S)
	w.f("\tGuard  string")
	w.f("\tAction string")
	w.f("\tHolds  func(f Funcs, e %s, ev %s) bool", e.Name, E)
	w.f("\tApply  func(f Funcs, e %s, ev %s) %s", e.Name, E, e.Name)
	w.f("}")
	w.f("")
	events := map[string]spec.Event{}
	for _, ev := range sc.Events {
		events[ev.Name] = ev
	}
	call := func(fn string, ev spec.Event) (pre, expr string) {
		f := g.c.Function(fn)
		args := []string{"e"}
		for _, p := range f.Params[1:] {
			args = append(args, "x."+pascal(p.Name))
		}
		if len(args) > 1 {
			pre = fmt.Sprintf("x := ev.(%s)\n", e.Name+pascal(ev.Name))
		}
		return pre, fmt.Sprintf("f.%s(%s)", pascal(fn), strings.Join(args, ", "))
	}
	w.f("// %sTransitions is the transition table, in spec order.", e.Name)
	w.f("var %sTransitions = []%s{", e.Name, T)
	for _, tr := range sc.Transitions {
		ev := events[tr.Event]
		w.f("\t{")
		w.f("\t\tFrom: %s%s, Event: %q, To: %s%s, Guard: %q, Action: %q,", S, pascal(tr.From), tr.Event, S, pascal(tr.To), tr.Guard, tr.Action)
		if tr.Guard != "" {
			pre, expr := call(tr.Guard, ev)
			w.f("\t\tHolds: func(f Funcs, e %s, ev %s) bool {", e.Name, E)
			w.f("\t\t\t%sreturn %s", pre, expr)
			w.f("\t\t},")
		}
		if tr.Action != "" {
			pre, expr := call(tr.Action, ev)
			w.f("\t\tApply: func(f Funcs, e %s, ev %s) %s {", e.Name, E, e.Name)
			w.f("\t\t\t%sreturn %s", pre, expr)
			w.f("\t\t},")
		}
		w.f("\t},")
	}
	w.f("}")
	w.f("")
	w.f("// %sPair is a state and an event name.", e.Name)
	w.f("type %sPair struct {", e.Name)
	w.f("\tState %s", S)
	w.f("\tEvent string")
	w.f("}")
	w.f("")
	w.f("// %sForbidden lists every pair the statechart rejects: the forbidden", e.Name)
	w.f("// events of each non-final state, and every event in each final state.")
	w.f("var %sForbidden = []%sPair{", e.Name, e.Name)
	forbidden := map[string]map[string]bool{}
	for _, f := range sc.Forbidden {
		forbidden[f.State] = map[string]bool{}
		for _, ev := range f.Events {
			forbidden[f.State][ev] = true
		}
	}
	for _, s := range sc.States {
		for _, ev := range sc.Events {
			if s.Final || forbidden[s.Name][ev.Name] {
				w.f("\t{%s%s, %q},", S, pascal(s.Name), ev.Name)
			}
		}
	}
	w.f("}")
	w.f("")

	w.f("// %sSelect returns the index in %sTransitions of the transition that", e.Name, e.Name)
	w.f("// fires, or ErrForbidden / ErrNoTransition.")
	w.f("func %sSelect(f Funcs, state %s, e %s, ev %s) (int, error) {", e.Name, S, e.Name, E)
	w.f("\tname := ev.EventName()")
	w.f("\tlisted := false")
	w.f("\tfor i, t := range %sTransitions {", e.Name)
	w.f("\t\tif t.From != state || t.Event != name {")
	w.f("\t\t\tcontinue")
	w.f("\t\t}")
	w.f("\t\tlisted = true")
	w.f("\t\tif t.Holds == nil || t.Holds(f, e, ev) {")
	w.f("\t\t\treturn i, nil")
	w.f("\t\t}")
	w.f("\t}")
	w.f("\tif listed {")
	w.f("\t\treturn -1, ErrNoTransition")
	w.f("\t}")
	w.f("\treturn -1, ErrForbidden")
	w.f("}")
	w.f("")

	w.f("// %sViolated returns the name of the first invariant e breaks, or \"\".", e.Name)
	w.f("func %sViolated(f Funcs, e %s) string {", e.Name, e.Name)
	for _, inv := range e.Invariants {
		w.f("\tif !f.%s(e) {", pascal(inv))
		w.f("\t\treturn %q", inv)
		w.f("\t}")
	}
	w.f("\treturn \"\"")
	w.f("}")
	w.f("")

	w.f("// %sStep applies ev to e in state: it selects the transition, runs its", e.Name)
	w.f("// action and checks the invariants. On any error it returns state and e")
	w.f("// unchanged.")
	w.f("func %sStep(f Funcs, state %s, e %s, ev %s) (%s, %s, error) {", e.Name, S, e.Name, E, S, e.Name)
	w.f("\ti, err := %sSelect(f, state, e, ev)", e.Name)
	w.f("\tif err != nil {")
	w.f("\t\treturn state, e, err")
	w.f("\t}")
	w.f("\tt := %sTransitions[i]", e.Name)
	w.f("\tnext := e")
	w.f("\tif t.Apply != nil {")
	w.f("\t\tnext = t.Apply(f, e, ev)")
	w.f("\t}")
	w.f("\tif name := %sViolated(f, next); name != \"\" {", e.Name)
	w.f("\t\treturn state, e, &InvariantError{Entity: %q, Invariant: name}", e.Name)
	w.f("\t}")
	w.f("\treturn t.To, next, nil")
	w.f("}")
	return w
}

// ---- derived tests ----

func (g *ctxGen) derivedFile(entities []spec.Entity) *writer {
	w := &writer{}
	g.header(w)
	w.f("// Package %s holds the tests derived from the %q statecharts. They", g.testPkg(), g.c.Context)
	w.f("// take an implementation of %s.Funcs and a Samples value written by hand:", g.pkg)
	w.f("// the entities and event values at the boundaries the rules name.")
	w.f("package %s", g.testPkg())
	w.f("")
	g.imports(w, []string{"errors", "fmt", "reflect", "testing"}, true)
	t := typer{c: g.c, qual: g.pkg + "."}
	for _, e := range entities {
		sc := e.Statechart
		S := g.pkg + "." + e.Name + "State"
		P := e.Name + "Samples"
		C := e.Name + "Case"
		w.f("// %s is an entity and an event to apply to it.", C)
		w.f("type %s struct {", C)
		w.f("\tEntity %s", t.goType(e.Name))
		w.f("\tEvent  %s", t.goType(e.Name+"Event"))
		w.f("}")
		w.f("")
		w.f("// %s supplies the inputs the derived tests need for %s: entities and", P, e.Name)
		w.f("// events at the boundaries the rules name, written by hand.")
		w.f("//")
		w.f("// Fire(i): cases where the guard of transition i holds and no earlier")
		w.f("// transition for the same state and event does; every boundary the rule")
		w.f("// has, from the inside.")
		w.f("// Block(i): cases where the guard of transition i is false; every")
		w.f("// boundary the rule has, from the outside (one case per side).")
		w.f("// Forbid: any entity valid for the state, with the event.")
		w.f("// Fire and Block must return at least one case.")
		w.f("//")
		w.f("// Transitions, in order:")
		for i, tr := range sc.Transitions {
			guard := ""
			if tr.Guard != "" {
				guard = " [" + tr.Guard + "]"
			}
			w.f("//   %d: %s --%s--> %s%s", i, tr.From, tr.Event, tr.To, guard)
		}
		w.f("type %s interface {", P)
		w.f("\tFire(i int) []%s", C)
		w.f("\tBlock(i int) []%s", C)
		w.f("\tForbid(state %s, event string) %s", S, C)
		w.f("}")
		w.f("")
		pk := g.pkg + "."
		w.f("// %s runs every derived test for %s against f: every transition fires with its", e.Name, e.Name)
		w.f("// action's result, every guard is false at its boundary, every forbidden")
		w.f("// pair is rejected, and the invariants hold after each step.")
		w.f("func %s(t *testing.T, f %sFuncs, s %s) {", e.Name, pk, P)
		w.f("\tt.Helper()")
		w.f("\tfor i, tr := range %s%sTransitions {", pk, e.Name)
		w.f("\t\ti, tr := i, tr")
		w.f("\t\tt.Run(fmt.Sprintf(\"fire/%%d %%s --%%s--> %%s\", i, tr.From, tr.Event, tr.To), func(t *testing.T) {")
		w.f("\t\t\tcases := s.Fire(i)")
		w.f("\t\t\tif len(cases) == 0 {")
		w.f("\t\t\t\tt.Fatal(\"samples gave no case\")")
		w.f("\t\t\t}")
		w.f("\t\t\tfor k, c := range cases {")
		w.f("\t\t\t\tk, c := k, c")
		w.f("\t\t\t\tt.Run(fmt.Sprint(k), func(t *testing.T) {")
		w.f("\t\t\t\t\te, ev := c.Entity, c.Event")
		w.f("\t\t\t\tif ev.EventName() != tr.Event {")
		w.f("\t\t\t\t\tt.Fatalf(\"sample event is %%q, want %%q\", ev.EventName(), tr.Event)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tgot, err := %s%sSelect(f, tr.From, e, ev)", pk, e.Name)
		w.f("\t\t\t\tif err != nil || got != i {")
		w.f("\t\t\t\t\tt.Fatalf(\"selected transition %%d, error %%v; want %%d\", got, err, i)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tstate, next, err := %s%sStep(f, tr.From, e, ev)", pk, e.Name)
		w.f("\t\t\t\tif err != nil {")
		w.f("\t\t\t\t\tt.Fatal(err)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tif state != tr.To {")
		w.f("\t\t\t\t\tt.Fatalf(\"state %%s, want %%s\", state, tr.To)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\twant := e")
		w.f("\t\t\t\tif tr.Apply != nil {")
		w.f("\t\t\t\t\twant = tr.Apply(f, e, ev)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tif !reflect.DeepEqual(next, want) {")
		w.f("\t\t\t\t\tt.Fatalf(\"entity %%+v, want %%+v\", next, want)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tif name := %s%sViolated(f, next); name != \"\" {", pk, e.Name)
		w.f("\t\t\t\t\tt.Fatalf(\"invariant %%s broken after the step\", name)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\t})")
		w.f("\t\t\t}")
		w.f("\t\t})")
		w.f("\t\tif tr.Holds == nil {")
		w.f("\t\t\tcontinue")
		w.f("\t\t}")
		w.f("\t\tt.Run(fmt.Sprintf(\"block/%%d %%s --%%s--> %%s [%%s]\", i, tr.From, tr.Event, tr.To, tr.Guard), func(t *testing.T) {")
		w.f("\t\t\tcases := s.Block(i)")
		w.f("\t\t\tif len(cases) == 0 {")
		w.f("\t\t\t\tt.Fatal(\"samples gave no case\")")
		w.f("\t\t\t}")
		w.f("\t\t\tfor k, c := range cases {")
		w.f("\t\t\t\tk, c := k, c")
		w.f("\t\t\t\tt.Run(fmt.Sprint(k), func(t *testing.T) {")
		w.f("\t\t\t\t\te, ev := c.Entity, c.Event")
		w.f("\t\t\t\tif ev.EventName() != tr.Event {")
		w.f("\t\t\t\t\tt.Fatalf(\"sample event is %%q, want %%q\", ev.EventName(), tr.Event)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tif tr.Holds(f, e, ev) {")
		w.f("\t\t\t\t\tt.Fatalf(\"guard %%s holds, want false\", tr.Guard)")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\tif got, _ := %s%sSelect(f, tr.From, e, ev); got == i {", pk, e.Name)
		w.f("\t\t\t\t\tt.Fatal(\"transition fired although its guard is false\")")
		w.f("\t\t\t\t}")
		w.f("\t\t\t\t})")
		w.f("\t\t\t}")
		w.f("\t\t})")
		w.f("\t}")
		w.f("\tfor _, p := range %s%sForbidden {", pk, e.Name)
		w.f("\t\tp := p")
		w.f("\t\tt.Run(fmt.Sprintf(\"forbid/%%s %%s\", p.State, p.Event), func(t *testing.T) {")
		w.f("\t\t\tc := s.Forbid(p.State, p.Event)\n\t\t\te, ev := c.Entity, c.Event")
		w.f("\t\t\tif ev.EventName() != p.Event {")
		w.f("\t\t\t\tt.Fatalf(\"sample event is %%q, want %%q\", ev.EventName(), p.Event)")
		w.f("\t\t\t}")
		w.f("\t\t\tstate, next, err := %s%sStep(f, p.State, e, ev)", pk, e.Name)
		w.f("\t\t\tif !errors.Is(err, %sErrForbidden) {", pk)
		w.f("\t\t\t\tt.Fatalf(\"error %%v, want ErrForbidden\", err)")
		w.f("\t\t\t}")
		w.f("\t\t\tif state != p.State || !reflect.DeepEqual(next, e) {")
		w.f("\t\t\t\tt.Fatal(\"a rejected event changed the state or the entity\")")
		w.f("\t\t\t}")
		w.f("\t\t})")
		w.f("\t}")
		w.f("}")
		w.f("")
	}
	return w
}

