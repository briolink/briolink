func (g *ctxGen) stubsFile() *writer {
	w := &writer{}
	g.header(w)
	w.f("// Package stubs is the starting point for implementing %s.Funcs: one", g.pkg)
	w.f("// file per function, each panicking until filled. Copy the files into the")
	w.f("// project's own package (domain/%s), drop the DO NOT EDIT line, and fill", g.c.Context)
	w.f("// them; the files here are regenerated, so never edit them in place.")
	w.f("package stubs")
	w.f("")
	g.imports(w, nil, true)
	w.f("// Impl implements %s.Funcs with stubs that panic.", g.pkg)
	w.f("type Impl struct{}")
	w.f("")
	w.f("var _ %s.Funcs = Impl{}", g.pkg)
	return w
}

func (g *ctxGen) stubFile(f spec.Function) *writer {
	w := &writer{}
	g.header(w)
	w.f("package stubs")
	w.f("")
	var ts []string
	for _, p := range f.Params {
		ts = append(ts, p.Type)
	}
	for _, r := range f.Returns {
		ts = append(ts, r.Type)
	}
	timePkg, ctx := uses(ts...)
	var std []string
	if timePkg {
		std = append(std, "time")
	}
	g.imports(w, std, ctx)
	t := typer{c: g.c, qual: g.pkg + "."}
	w.f("// %s is a %s.", pascal(f.Name), f.Kind)
	if f.Doc != "" {
		w.f("// %s", oneLine(f.Doc))
	}
	w.f("//")
	w.f("// Rules:")
	for _, r := range f.Rules {
		w.f("//   - %s", oneLine(r))
	}
	sig := g.sig(t, f)
	w.f("func (Impl) %s {", sig)
	w.f("\tpanic(%q)", "not implemented: "+f.Name)
	w.f("}")
	return w
}

// ---- helpers ----

func doc(w *writer, name, d, fallback string) {
	if d == "" {
		w.f("// %s %s", name, fallback)
		return
	}
	w.f("// %s %s", name, lowerFirst(oneLine(d)))
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// pascal turns a snake_case spec name into a PascalCase Go identifier.
func pascal(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// snake turns a PascalCase type name into a snake_case file name.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
