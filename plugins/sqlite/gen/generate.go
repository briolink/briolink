// Input is what Generate needs: a project's migrated schema (every
// migrations/*.sql file, concatenated in migration order) and its parsed
// spec/queries/*.sql statements.
type Input struct {
	Package string // the generated package's name, e.g. "sqlitegen"
	Schema  string // the project's migrations, concatenated in order
	Queries []spec.Query
}

// Generate checks every query in in.Queries against in.Schema — every
// table STRICT, double-quoted strings off, each statement's parameter and
// result-column shape compared with its header (docs/2-architecture.md §
// Specs and generators) — and returns an error listing every problem found,
// without writing anything, if any statement fails.
//
// On success it returns the generated files, keyed by name relative to the
// project's gen/ directory ("Generated code goes to gen/ with a DO NOT EDIT
// header"), gofmt'd: queries.go (typed functions) and queries_check_test.go
// (a test that repeats this same check against the schema it was generated
// from, so a migration edited without regenerating fails the build).
func Generate(ctx context.Context, in Input) (map[string][]byte, error) {
	if err := spec.Unique(in.Queries); err != nil {
		return nil, err
	}
	db, err := Open(ctx, in.Schema)
	if err != nil {
		return nil, fmt.Errorf("applying migrations: %w", err)
	}
	defer db.Close()

	var l check.List
	for _, p := range RequireStrict(ctx, db) {
		l.Addf("schema", "%s", p)
	}
	for _, q := range in.Queries {
		for _, p := range Check(ctx, db, q) {
			l.Addf(fmt.Sprintf("%s:%d", q.File, q.Line), "%s: %s", q.Name, p)
		}
	}
	if err := l.Err(); err != nil {
		return nil, err
	}

	queries := append([]spec.Query(nil), in.Queries...)
	sort.Slice(queries, func(i, j int) bool { return queries[i].Name < queries[j].Name })

	code, err := render(queriesTemplate, struct {
		Package  string
		UsesTime bool
		Queries  []spec.Query
	}{in.Package, usesTime(queries), queries})
	if err != nil {
		return nil, fmt.Errorf("rendering queries.go: %w", err)
	}
	test, err := render(checkTestTemplate, struct {
		Package string
		Schema  string
		Queries []spec.Query
	}{in.Package, in.Schema, queries})
	if err != nil {
		return nil, fmt.Errorf("rendering queries_check_test.go: %w", err)
	}
	return map[string][]byte{
		"queries.go":            code,
		"queries_check_test.go": test,
	}, nil
}

// usesTime reports whether any parameter or column maps to a time type, so
// the generated file imports "time" only when it needs it.
func usesTime(queries []spec.Query) bool {
	for _, q := range queries {
		for _, c := range append(append([]spec.Column(nil), q.Params...), q.Columns...) {
			if strings.TrimPrefix(c.Type, "?") == "time" {
				return true
			}
		}
	}
	return false
}

// goType is the Go type a spec column or parameter type maps to: the plain
// type for a non-nullable one, or a database/sql Null* wrapper (a Valuer
// and Scanner, so it works on both sides) for one prefixed "?". bytes is
// its own nil-safe zero value, so it never needs a wrapper.
func goType(specType string) string {
	base, nullable := strings.CutPrefix(specType, "?")
	if base == "bytes" {
		return "[]byte"
	}
	if !nullable {
		return map[string]string{
			"string": "string",
			"int":    "int64",
			"float":  "float64",
			"bool":   "bool",
			"time":   "time.Time",
		}[base]
	}
	return map[string]string{
		"string": "sql.NullString",
		"int":    "sql.NullInt64",
		"float":  "sql.NullFloat64",
		"bool":   "sql.NullBool",
		"time":   "sql.NullTime",
	}[base]
}

// pascal turns a snake_case spec name into a PascalCase Go identifier.
func pascal(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func rowType(name string) string { return pascal(name) + "Row" }

var funcs = template.FuncMap{
	"pascal":  pascal,
	"goType":  goType,
	"rowType": rowType,
}

func render(tmpl *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}

var queriesTemplate = template.Must(template.New("queries.go").Funcs(funcs).Parse(`
// Code generated by plugins/sqlite/gen from spec/queries/*.sql. DO NOT EDIT.
package {{.Package}}

import (
	"context"
	"database/sql"
{{- if .UsesTime}}
	"time"
{{- end}}
)

// DBTX is the *sql.DB or *sql.Tx method set Queries needs.
type DBTX interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
}

// New wraps db (an *sql.DB or an *sql.Tx) with the generated statements.
func New(db DBTX) *Queries { return &Queries{db: db} }

type Queries struct{ db DBTX }

{{range .Queries}}
{{if .Columns}}
type {{rowType .Name}} struct {
{{range .Columns}}	{{pascal .Name}} {{goType .Type}}
{{end}}}
{{end}}
const {{.Name}}SQL = {{printf "%q" .SQL}}

{{if eq .Cardinality ":exec"}}
func (q *Queries) {{pascal .Name}}(ctx context.Context{{range .Params}}, {{.Name}} {{goType .Type}}{{end}}) error {
	_, err := q.db.ExecContext(ctx, {{.Name}}SQL{{range .Params}}, {{.Name}}{{end}})
	return err
}
{{else if eq .Cardinality ":one"}}
func (q *Queries) {{pascal .Name}}(ctx context.Context{{range .Params}}, {{.Name}} {{goType .Type}}{{end}}) ({{rowType .Name}}, error) {
	var row {{rowType .Name}}
	err := q.db.QueryRowContext(ctx, {{.Name}}SQL{{range .Params}}, {{.Name}}{{end}}).Scan({{range .Columns}}&row.{{pascal .Name}}, {{end}})
	return row, err
}
{{else}}
func (q *Queries) {{pascal .Name}}(ctx context.Context{{range .Params}}, {{.Name}} {{goType .Type}}{{end}}) ([]{{rowType .Name}}, error) {
	rows, err := q.db.QueryContext(ctx, {{.Name}}SQL{{range .Params}}, {{.Name}}{{end}})
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []{{rowType .Name}}
	for rows.Next() {
		var row {{rowType .Name}}
		if err := rows.Scan({{range .Columns}}&row.{{pascal .Name}}, {{end}}); err != nil {
			return nil, err
		}
		out = append(out, row)
	}
	return out, rows.Err()
}
{{end}}
{{end}}
`))

